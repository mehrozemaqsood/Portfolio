import { chromium } from 'playwright';
const [,,pg,y,h,out] = process.argv;
const b = await chromium.launch({executablePath:'/opt/pw-browsers/chromium-1194/chrome-linux/chrome'});
const p = await b.newPage({ viewport:{width:390,height:800} });
await p.goto('http://localhost:4321/'+pg,{waitUntil:'networkidle'});
await p.evaluate(async(y)=>{window.scrollTo(0,+y-200);await new Promise(r=>setTimeout(r,800))},y);
await p.evaluate(async(y)=>{window.scrollTo(0,+y);await new Promise(r=>setTimeout(r,1500))},y);
await p.screenshot({path:out,clip:{x:0,y:+y,width:390,height:Math.min(+h,800)},fullPage:true});
console.log(await p.evaluate(()=>[...document.querySelectorAll('.stage-m img')].filter(i=>!i.complete||i.naturalWidth==0).map(i=>i.currentSrc||i.src)));
await b.close();
